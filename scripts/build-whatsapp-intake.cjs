'use strict';
const fs = require('node:fs');
const path = require('node:path');
const root = path.join(__dirname, '..');
const validation = fs.readFileSync(path.join(root, 'supabase/functions/dg-inbox/media-validation.mjs'), 'utf8').replace(/^export /gm, '');
for (const [source, target] of [['parse-owner-message.js', 'parse-owner-message.code.js'], ['add-owner-file.js', 'add-owner-file.code.js']]) {
  const body = fs.readFileSync(path.join(root, 'n8n', source), 'utf8');
  fs.writeFileSync(path.join(root, 'n8n', target), '// GENERATED by scripts/build-whatsapp-intake.cjs; edit the source files instead.\n' + validation + '\n' + body);
}
const handler = fs.readFileSync(path.join(root, 'supabase/functions/dg-inbox/inbox-handler.mjs'), 'utf8').replace(/^import .*;\r?\n/gm, '').replace(/^export /gm, '');
const bootstrap = `import "jsr:@supabase/functions-js/edge-runtime.d.ts";
import { createClient } from "npm:@supabase/supabase-js@2.45.4";
const sb = createClient(Deno.env.get("SUPABASE_URL")!, Deno.env.get("SUPABASE_SERVICE_ROLE_KEY")!, { auth: { persistSession: false } });
let cachedKey: string | null = null;
async function getKey(){
  if(cachedKey) return cachedKey;
  const { data } = await sb.from("dg_inbox_config").select("value").eq("key", "n8n_key").single();
  cachedKey = data?.value || null;
  return cachedKey;
}
`;
fs.writeFileSync(path.join(root, 'supabase/functions/dg-inbox/index.ts'), '// GENERATED standalone deployment entry; edit media-validation.mjs/inbox-handler.mjs and run scripts/build-whatsapp-intake.cjs.\n' + bootstrap + '\n' + validation + '\n' + handler + '\nDeno.serve(createInboxHandler({ sb, getKey }));\n');
