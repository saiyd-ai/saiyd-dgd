'use strict';
// Supabase's browser editor accepts a single file. Keep the reviewed modules
// as source and generate an equivalent pinned-dependency deployment entry.
const fs = require('node:fs');
const path = require('node:path');
const root = path.join(__dirname, '..');
const modules = [
  'supabase/functions/dg-inbox/media-validation.mjs',
  'supabase/functions/skyd-prepare/skyd-fields.mjs',
  'supabase/functions/skyd-prepare/skyd-runtime.mjs',
  'supabase/functions/skyd-prepare/skyd-handler.mjs',
  'supabase/functions/skyd-prepare/skyd-awb-pdf.mjs',
];
const source = modules.map(file => '// SOURCE: ' + file + '\n' + fs.readFileSync(path.join(root, file), 'utf8')
  .replace(/^import .*;\r?\n/gm, '').replace(/^export /gm, '')
  // Deno's bundler also resolves literal dynamic imports in unused branches.
  // The browser deployment has no Node package.json/import map; reuse its
  // explicitly pinned top-level dependency instead of the module's Node fallback.
  .replace("return import('pdf-lib');", 'return pdfLib;')).join('\n\n');
const bootstrap = `import "jsr:@supabase/functions-js/edge-runtime.d.ts";
import { createClient } from "npm:@supabase/supabase-js@2.45.4";
import * as pdfLib from "npm:pdf-lib@1.17.1";
import * as XLSX from "https://cdn.sheetjs.com/xlsx-0.20.3/package/xlsx.mjs";
const sb = createClient(Deno.env.get("SUPABASE_URL")!, Deno.env.get("SUPABASE_SERVICE_ROLE_KEY")!, { auth: { persistSession: false } });
let cachedKey: string | null = null;
async function getKey(){
  if(cachedKey) return cachedKey;
  const { data } = await sb.from("dg_inbox_config").select("value").eq("key", "n8n_key").single();
  cachedKey = data?.value || null;
  return cachedKey;
}
`;
const runtime = `
async function readPdf(bytes){
  // Encrypted/broken PDFs fail; never bypass encryption or discard pages.
  const document = await pdfLib.PDFDocument.load(bytes);
  return { pages: document.getPageCount() };
}
async function readExcel(bytes){
  // Signature/container admission runs first. SheetJS does not execute formulas
  // or macros. Read the whole supported workbook and reject, rather than
  // truncate, sources beyond the documented sheet/text limits.
  const book = XLSX.read(bytes, { type: 'array', dense: true, cellFormula: false, cellHTML: false, bookVBA: false });
  if(book.SheetNames.length>SKYD_LIMITS.excelSheets) throw new SkydInputError('Workbook has more than 4 sheets. Use a complete smaller workbook or prepare manually.');
  let text='';
  for(const name of book.SheetNames){
    const sheet=book.Sheets[name];
    if(sheet['!ref']){
      const range=XLSX.utils.decode_range(sheet['!ref']);
      const cells=(range.e.r-range.s.r+1)*(range.e.c-range.s.c+1);
      // Prevent sparse/forged sheet dimensions from allocating unbounded CSV.
      // This rejects the entire source, never limits the rows being read.
      if(!Number.isSafeInteger(cells) || cells>SKYD_LIMITS.excelChars) throw new SkydInputError('Workbook used range exceeds the extraction limit. Use a complete smaller workbook or prepare manually.');
    }
    // Hidden rows/sheets are included as source evidence, not silently skipped.
    text += 'SHEET '+name+'\\n'+XLSX.utils.sheet_to_csv(sheet,{blankrows:true})+'\\n';
    if(text.length>SKYD_LIMITS.excelChars) throw new SkydInputError('Workbook exceeds 12,000 extracted characters. Use a complete smaller workbook or prepare manually.');
  }
  return { sheets: book.SheetNames.length, text };
}
const prepareSnapshot=createSkydPreparation({sb,readPdf,readExcel});
Deno.serve(createSkydHandler({sb,getKey,prepareSnapshot,renderPdf:(fields,options)=>renderAwbDraftPdf(fields,{...options,pdfLib})}));
`;
const output = '// GENERATED by scripts/build-skyd-prepare.cjs; edit the source modules instead.\n' + bootstrap + '\n' + source + '\n' + runtime;
fs.writeFileSync(path.join(root, 'supabase/functions/skyd-prepare/index.ts'), output);
